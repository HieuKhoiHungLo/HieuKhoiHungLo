-- 1. Nâng cấp Địa chính (Geography)
-- Tạo bảng Huyện
CREATE TABLE public.dm_huyen (
    ma_huyen TEXT PRIMARY KEY,
    ten_huyen TEXT NOT NULL,
    ma_tinh TEXT REFERENCES public.dm_tinh(ma_tinh)
);

-- Cập nhật bảng Xã: Thêm cột ma_huyen
ALTER TABLE public.dm_xa ADD COLUMN ma_huyen TEXT REFERENCES public.dm_huyen(ma_huyen);
-- Note: Sau này cần script để update data ma_huyen cho các xã hiện có

-- Cập nhật bảng Thí sinh: Thêm cột ma_huyen_thuong_tru
ALTER TABLE public.thi_sinh ADD COLUMN ma_huyen_thuong_tru TEXT REFERENCES public.dm_huyen(ma_huyen);


-- 2. Nâng cấp Tuyển sinh (Admissions)
-- Tạo bảng Năm tuyển sinh
CREATE TABLE public.dm_nam_tuyen_sinh (
    nam INT PRIMARY KEY,
    mo_ta TEXT,
    trang_thai TEXT DEFAULT 'Active', -- Active, Inactive
    created_at TIMESTAMPTZ DEFAULT NOW()
);

